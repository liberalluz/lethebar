#!/usr/bin/env python3
"""Export the Godot project into an unsigned iOS build.

Godot can only export an iOS app where Xcode exists, so this script refuses on
every other host instead of producing a file that cannot be built. The CI path
is Codemagic (``codemagic.yaml``); the runbook is ``docs/runbooks/ios.md``.
"""
import argparse
import os
import platform
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / "app"
PRESET = "iOS"
OUT = ROOT / "build" / "ios"
PRESET_SOURCE = ROOT / "infra" / "export_presets" / "ios.cfg"
PRESET_STAGED = APP / "export_presets.cfg"
GODOT_VERSION = "4.7.2.stable"


def refusal(host: str) -> str:
    """The sentence a non-Mac host gets, or an empty string on macOS."""
    if host == "darwin":
        return ""
    return (
        "the iOS exporter runs only on macOS: Godot needs Xcode, so build on a "
        "Mac or let Codemagic do it (docs/runbooks/ios.md)"
    )


def templates_dir(home: Path) -> Path:
    return home / "Library" / "Application Support" / "Godot" / "export_templates" / GODOT_VERSION


def export_command(godot: str, app: Path, preset: str, out: Path) -> list:
    return [godot, "--headless", "--path", str(app), "--export-release", preset, str(out)]


def xcode_command(project: Path, scheme: str, derived: Path, sdk: str = "iphoneos") -> list:
    return [
        "xcodebuild",
        "-project", str(project),
        "-scheme", scheme,
        "-configuration", "Release",
        "-sdk", sdk,
        "-derivedDataPath", str(derived),
        "CODE_SIGNING_ALLOWED=NO",
        "CODE_SIGNING_REQUIRED=NO",
    ]


def package_command(product: Path, payload: Path, ipa: Path) -> list:
    return [
        "bash", "-c",
        f"rm -rf {payload} {ipa} && mkdir -p {payload} && "
        f"cp -R {product} {payload}/ && cd {payload.parent} && "
        f"zip -qry {ipa.name} Payload",
    ]


def stage_preset(source: Path, staged: Path) -> None:
    """Godot only reads ``app/export_presets.cfg``; stage the source for the export."""
    if staged.exists():
        print(f"{staged} already exists; remove it before exporting (it is generated by this script)")
        raise SystemExit(2)
    staged.write_text(source.read_text(encoding="utf-8"), encoding="utf-8")


def unstage_preset(staged: Path) -> None:
    if staged.exists():
        staged.unlink()


STAGE = ROOT / "infra" / "stage_builtin.py"
BUILTIN = ROOT / "content" / "builtin"


def stage_command() -> list:
    """The built-in pack is generated, so a clean checkout has no zip to export."""
    return [sys.executable, str(STAGE)]


def build_commands(godot: str, scheme: str) -> list:
    project = OUT / "Lethebar.xcodeproj"
    derived = OUT / "build"
    product = derived / "Build" / "Products" / "Release-iphoneos" / "Lethebar.app"
    ipa = OUT / "Lethebar-unsigned.ipa"
    return [
        stage_command(),
        export_command(godot, APP, PRESET, project),
        xcode_command(project, scheme, derived),
        package_command(product, OUT / "Payload", ipa),
    ]


def self_test() -> int:
    failures = []
    if refusal("win32") == "":
        failures.append("a Windows host was not refused")
    if refusal("darwin") != "":
        failures.append("macOS was refused")
    command = export_command("godot", APP, PRESET, OUT / "Lethebar.xcodeproj")
    if "--export-release" not in command or PRESET not in command:
        failures.append("the export command lost the preset")
    build = xcode_command(OUT / "Lethebar.xcodeproj", "Lethebar", OUT / "build")
    if "CODE_SIGNING_ALLOWED=NO" not in build:
        failures.append("the Xcode command would try to sign")
    package = package_command(OUT / "Lethebar.app", OUT / "Payload", OUT / "Lethebar-unsigned.ipa")
    if "Lethebar-unsigned.ipa" not in " ".join(package):
        failures.append("the package step lost the ipa name")
    if PRESET_SOURCE.name != "ios.cfg" or PRESET_STAGED.name != "export_presets.cfg":
        failures.append("the preset source or the staged path moved")
    if "stage_preset" not in globals() or "unstage_preset" not in globals():
        failures.append("staging helpers are missing")
    commands = build_commands("godot", "Lethebar")
    if len(commands) != 4:
        failures.append("the build chain lost a step")
    if not commands[0][-1].endswith("stage_builtin.py"):
        failures.append("the built-in pack is not staged before the export")
    if STAGE.name != "stage_builtin.py":
        failures.append("the staging script moved")
    for failure in failures:
        print(f"[fail] {failure}")
    if not failures:
        print("self-test: 9 cases, 0 failure(s)")
    return 1 if failures else 0


def main(argv: list) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--godot", default=os.environ.get("GODOT_BIN", "godot"))
    parser.add_argument("--scheme", default="Lethebar")
    parser.add_argument("--check", action="store_true", help="only report whether this host can build")
    parser.add_argument("--dry-run", action="store_true", help="print the commands and stop")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args(argv)

    if args.self_test:
        return self_test()

    host = platform.system().lower()
    message = refusal(host)
    if message:
        print(message)
        return 2
    templates = templates_dir(Path.home())
    if not (templates / "ios.zip").is_file():
        print(f"the iOS export templates are missing: install {GODOT_VERSION} templates at {templates}")
        return 2
    if not any(BUILTIN.iterdir()):
        print(f"no built-in pack to stage under {BUILTIN}")
        return 2
    if args.check:
        print("ok: macOS, Xcode and the iOS export templates are present")
        return 0

    commands = build_commands(args.godot, args.scheme)
    if args.dry_run:
        print(f"copy {PRESET_SOURCE} -> {PRESET_STAGED}")
        for command in commands:
            print(" ".join(command))
        return 0

    OUT.mkdir(parents=True, exist_ok=True)
    stage_preset(PRESET_SOURCE, PRESET_STAGED)
    try:
        for command in commands:
            subprocess.run(command, check=True, cwd=ROOT)
    finally:
        unstage_preset(PRESET_STAGED)
    print(f"unsigned ipa: {ipa}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
