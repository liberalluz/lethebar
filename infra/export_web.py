#!/usr/bin/env python3
"""Export the web build with the project's single export preset.

Godot only reads `export_presets.cfg` from the project root, but the preset is
source that belongs in `infra/` (SDD §2.2: "export presets, build and check
scripts"). This script stages the preset into the project root for the duration
of the export and removes the staged copy afterwards.

The export templates are not in the repository. They live in a machine-local
directory that plays the role of `%APPDATA%`, so nothing here hardcodes a path.

Environment:
    GODOT_BIN               Godot editor binary. Defaults to `godot` on PATH.
    GODOT_TEMPLATE_APPDATA  Directory that stands in for `%APPDATA%` and holds
                            `Godot/export_templates/<version>/`. Required for an
                            export; the script explains what is missing if unset.

Exit code is 0 only when Godot reported a successful export and the shell files
exist in the output directory.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
PROJECT_ROOT = REPO_ROOT / "app"
PRESET_SOURCE = REPO_ROOT / "infra" / "export_presets" / "web.cfg"
PRESET_STAGED = PROJECT_ROOT / "export_presets.cfg"
PRESET_NAME = "Web"
DEFAULT_OUTPUT = REPO_ROOT / "build" / "web"
EXPECTED_FILES = ("index.html", "index.js", "index.wasm", "index.pck")
SERVICE_WORKER = "index.service.worker.js"
PAYLOAD_FILES = ("index.wasm", "index.pck")


def godot_binary() -> str:
    return os.environ.get("GODOT_BIN", "godot")


def godot_version(binary: str) -> str:
    result = subprocess.run(
        [binary, "--version"], capture_output=True, text=True, encoding="utf-8"
    )
    if result.returncode != 0:
        raise SystemExit(
            f"cannot run {binary} --version; set GODOT_BIN to the Godot editor binary\n"
            f"{result.stderr.strip()}"
        )
    # "4.7.2.stable.official.ed1daf0bf" -> "4.7.2.stable", the template directory name
    raw = (result.stdout or result.stderr).strip()
    parts = raw.split(".")
    return ".".join(parts[:4])


def template_directory(binary: str) -> Path:
    appdata = os.environ.get("GODOT_TEMPLATE_APPDATA")
    if not appdata:
        raise SystemExit(
            "GODOT_TEMPLATE_APPDATA is not set; it must point at the directory that "
            "stands in for %APPDATA% and contains Godot/export_templates/<version>/"
        )
    version = godot_version(binary)
    directory = Path(appdata) / "Godot" / "export_templates" / version
    if not directory.is_dir():
        raise SystemExit(
            f"no export templates for Godot {version} at {directory}\n"
            "install them with the editor (Editor > Manage Export Templates) or "
            "unpack the .tpz release archive into that directory"
        )
    return directory


def stage_preset() -> None:
    if PRESET_STAGED.exists():
        raise SystemExit(
            f"{PRESET_STAGED} already exists; it is generated by this script. Remove it first."
        )
    shutil.copyfile(PRESET_SOURCE, PRESET_STAGED)


def run_export(binary: str, output: Path, appdata: Path) -> None:
    output.mkdir(parents=True, exist_ok=True)
    environment = dict(os.environ)
    # appdata is <APPDATA>/Godot/export_templates/<version>; Godot wants the root.
    environment["APPDATA"] = str(appdata.parents[2])
    command = [
        binary,
        "--path",
        str(PROJECT_ROOT),
        "--headless",
        "--export-release",
        PRESET_NAME,
        str(output / "index.html"),
    ]
    result = subprocess.run(
        command, capture_output=True, text=True, encoding="utf-8", env=environment
    )
    combined = f"{result.stdout}\n{result.stderr}"
    if result.returncode != 0 or "export failed" in combined.lower():
        tail = "\n".join(line for line in combined.splitlines() if line.strip())[-1500:]
        raise SystemExit(f"web export failed\n{tail}")


def precache_payload(output: Path) -> None:
    """Move the engine payload into the service worker's pre-cache list.

    Godot's generated worker splits its lists: `CACHED_FILES` is fetched during
    `install`, while `CACHEABLE_FILES` is only stored when the page happens to
    request it through the worker. A player who loads once and then goes offline
    would therefore miss `index.wasm` and `index.pck` — the only two files the
    app cannot start without. Offline reload is a `TC-OFF-001` promise, so the
    payload is pre-cached instead.

    The worker is generated, so this is a post-export edit rather than a source
    change; it fails loudly if the shape it edits ever changes.
    """
    worker = output / SERVICE_WORKER
    if not worker.is_file():
        raise SystemExit(
            f"{SERVICE_WORKER} is missing; enable progressive_web_app in the preset"
        )
    text = worker.read_text(encoding="utf-8")
    cached = re.search(r"const CACHED_FILES\s*=\s*\[(.*?)\];", text, re.S)
    cacheable = re.search(r"const CACHEABLE_FILES\s*=\s*\[(.*?)\];", text, re.S)
    if cached is None or cacheable is None:
        raise SystemExit(f"{SERVICE_WORKER} no longer has the lists this script edits")
    names = re.findall(r'"([^"]+)"', cached.group(1))
    lazy = re.findall(r'"([^"]+)"', cacheable.group(1))
    for name in lazy:
        if name not in names:
            names.append(name)
    missing = [name for name in PAYLOAD_FILES if name not in names]
    if missing:
        raise SystemExit(f"the worker does not know about {', '.join(missing)}")
    # The payload gets its own content-addressed caches (see
    # `layer_payload_caches`), so it must not also sit in the timestamped shell
    # cache: that cache is dropped on every publish, which is the waste this
    # batch removes.
    names = [name for name in names if name not in PAYLOAD_FILES]
    replacement = "const CACHED_FILES = [" + ", ".join(f'"{n}"' for n in names) + "];"
    # Replace the later span first: the earlier text is longer than what it was,
    # so applying the first edit first would shift the second span's offsets and
    # splice the file in the wrong place.
    spans = [
        (cacheable.start(), cacheable.end(), "const CACHEABLE_FILES = [];"),
        (cached.start(), cached.end(), replacement),
    ]
    for start, end, text_for_span in sorted(spans, reverse=True):
        text = text[:start] + text_for_span + text[end:]
    worker.write_text(text, encoding="utf-8")


NAVIGATION_FALLBACK = (
    "let cached = await cache.match(event.request);\n"
    "\t\t\t\tif (cached == null && isNavigate) {\n"
    "\t\t\t\t\t// A player arrives at the directory URL (/lethebar/), which is a\n"
    "\t\t\t\t\t// different cache key than index.html. Without this fallback every\n"
    "\t\t\t\t\t// navigation misses the cache, goes to the network and fails offline\n"
    "\t\t\t\t\t// (iOS Safari reports it as \"FetchEvent.respondWith received an\n"
    "\t\t\t\t\t// error: TypeError: Load failed\").\n"
    "\t\t\t\t\t//\n"
    "\t\t\t\t\t// Only a document URL gets the document. Answering any navigation\n"
    "\t\t\t\t\t// with it turned /lethebar/test-pack.zip into the game instead of a\n"
    "\t\t\t\t\t// download, because `isNavigate` covers every top level navigation.\n"
    "\t\t\t\t\tconst target = new URL(event.request.url).pathname;\n"
    "\t\t\t\t\tif (target.endsWith('/') || target.endsWith('/index.html')) {\n"
    "\t\t\t\t\t\tcached = await cache.match(CACHED_FILES[0]);\n"
    "\t\t\t\t\t}\n"
    "\t\t\t\t}\n"
)


def patch_navigation_fallback(output: Path) -> None:
    """Make an offline navigation to the site root find the cached document.

    `TC-OFF-001` says the page opens offline. The engine's worker caches
    `index.html`, but a navigation goes to the directory URL (`/lethebar/`),
    and `cache.match` compares whole URLs, so the lookup missed and the request
    fell through to the network. Desktop Chrome hid this because the smoke check
    navigated to `/index.html`; Safari on iOS is the environment the test plan
    names, and there it fails.

    The worker is generated, so this is a post-export edit; it fails loudly if
    the shape it edits ever changes.
    """
    worker = output / SERVICE_WORKER
    if not worker.is_file():
        raise SystemExit(f"{SERVICE_WORKER} is missing; the export did not produce it")
    text = worker.read_text(encoding="utf-8")
    anchor = "let cached = await cache.match(event.request);\n"
    if text.count(anchor) != 1:
        raise SystemExit(f"{SERVICE_WORKER} no longer has the lookup this script patches")
    text = text.replace(anchor, NAVIGATION_FALLBACK, 1)
    offline = "return caches.match(OFFLINE_URL);"
    if text.count(offline) != 1:
        raise SystemExit(f"{SERVICE_WORKER} no longer has the offline page fallback")
    text = text.replace(
        offline,
        "const document = await cache.match(CACHED_FILES[0]);\n"
        "\t\t\t\t\t\t\treturn document != null ? document : caches.match(OFFLINE_URL);",
        1,
    )
    worker.write_text(text, encoding="utf-8")


PAYLOAD_PREFIX = "Lethebar-payload-"

INSTALL_ANCHOR = (
    "event.waitUntil(caches.open(CACHE_NAME).then((cache) => cache.addAll(CACHED_FILES)));"
)
ACTIVATE_ANCHOR = (
    "return Promise.all(keys.filter((key) => key.startsWith(CACHE_PREFIX) && key !== CACHE_NAME)"
    ".map((key) => caches.delete(key)));"
)
MISSING_ANCHOR = "const missing = fullCache.some((v) => v === undefined);"
CACHE_OPEN_ANCHOR = "const cache = await caches.open(CACHE_NAME);"


def payload_digest(path: Path) -> str:
    """First twelve hex digits of the file's sha256, which names its cache."""
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()[:12]


def payload_cache_names(output: Path) -> dict[str, str]:
    """Cache name per payload file, derived from the bytes rather than the clock."""
    names: dict[str, str] = {}
    for name in PAYLOAD_FILES:
        path = output / name
        if not path.is_file():
            raise SystemExit(f"{name} is missing; the export did not produce it")
        stem = "wasm" if name.endswith(".wasm") else "pck"
        names[name] = f"{PAYLOAD_PREFIX}{stem}-{payload_digest(path)}"
    return names


def layer_payload_caches(output: Path) -> dict[str, str]:
    """Give each large file its own cache, named after its bytes.

    The engine's worker keeps everything in one cache whose name comes from the
    export timestamp, so publishing a build invalidates the whole cache and the
    39.5 MB `index.wasm` is downloaded again even when it did not change. Splitting
    the payload into content-addressed caches means a story-only build keeps the
    wasm cache, and a build that changes the engine replaces it.

    `activate` deletes payload caches that no longer appear in `PAYLOAD`, so the
    split does not accumulate one cache per publish.
    """
    worker = output / SERVICE_WORKER
    if not worker.is_file():
        raise SystemExit(f"{SERVICE_WORKER} is missing; the export did not produce it")
    names = payload_cache_names(output)
    text = worker.read_text(encoding="utf-8")

    for anchor in (INSTALL_ANCHOR, ACTIVATE_ANCHOR, MISSING_ANCHOR, CACHE_OPEN_ANCHOR):
        if text.count(anchor) != 1:
            raise SystemExit(f"{SERVICE_WORKER} no longer has {anchor[:40]}...")

    declarations = ",\n".join(
        f'\t"{name}": "{cache}"' for name, cache in names.items()
    )
    declaration_block = (
        f"\n\n// Each payload file sits in its own cache, named after its bytes.\n"
        f'const PAYLOAD_PREFIX = "{PAYLOAD_PREFIX}";\n'
        f"const PAYLOAD = {{\n{declarations}\n}};"
    )
    marker = "const CACHE_NAME = CACHE_PREFIX + CACHE_VERSION;"
    text = text.replace(marker, marker + declaration_block, 1)

    # The payload is not prefetched at install time on purpose. Installing a new
    # worker while the page is running already competes with the engine's
    # background write of `user://` to IndexedDB; add a 39.5 MB download to that
    # and a player's import can be lost before it lands. The game itself requests
    # both files on the first load, and the fetch branch below stores them, so
    # the payload caches fill from the player's own traffic.
    install = (
        "event.waitUntil(caches.open(CACHE_NAME).then((cache) => cache.addAll(CACHED_FILES)));"
    )
    text = text.replace(INSTALL_ANCHOR, install, 1)

    activate = (
        "const keep = Object.values(PAYLOAD);\n"
        "\t\t\treturn Promise.all(keys\n"
        "\t\t\t\t.filter((key) =>\n"
        "\t\t\t\t\t(key.startsWith(CACHE_PREFIX) && key !== CACHE_NAME) ||\n"
        "\t\t\t\t\t(key.startsWith(PAYLOAD_PREFIX) && !keep.includes(key)))\n"
        "\t\t\t\t.map((key) => caches.delete(key)));"
    )
    text = text.replace(ACTIVATE_ANCHOR, activate, 1)

    missing = (
        "const missing = fullCache.some((v) => v === undefined);\n"
        "\t\t\t\t// The payload is not in this cache; a navigation is only safe when\n"
        "\t\t\t\t// every payload file is already stored in its own cache.\n"
        "\t\t\t\tconst payloadMissing = (\n"
        "\t\t\t\t\tawait Promise.all(\n"
        "\t\t\t\t\t\tObject.keys(PAYLOAD).map(async (name) =>\n"
        "\t\t\t\t\t\t\t(await (await caches.open(PAYLOAD[name])).match(name)) === undefined)\n"
        "\t\t\t\t\t)\n"
        "\t\t\t\t).some(Boolean);"
    )
    text = text.replace(MISSING_ANCHOR, missing, 1)
    text = text.replace(
        "if (missing) {",
        "if (missing || payloadMissing) {",
        1,
    )

    lookup = (
        CACHE_OPEN_ANCHOR
        + "\n\t\t\t\tconst payloadCache = PAYLOAD[local];\n"
        "\t\t\t\tif (payloadCache !== undefined) {\n"
        "\t\t\t\t\tconst store = await caches.open(payloadCache);\n"
        "\t\t\t\t\tconst hit = await store.match(event.request);\n"
        "\t\t\t\t\tif (hit != null) {\n"
        "\t\t\t\t\t\treturn hit;\n"
        "\t\t\t\t\t}\n"
        "\t\t\t\t\tconst fetched = await fetch(event.request);\n"
        "\t\t\t\t\tif (fetched.ok) {\n"
        # A refused write used to be silent; the page can now ask why (REQ-031).
        "\t\t\t\t\t\tstore.put(event.request, fetched.clone()).catch((error) => {\n"
        "\t\t\t\t\t\t\tself.lethebarCacheError = String((error && error.message) || error);\n"
        "\t\t\t\t\t\t});\n"
        "\t\t\t\t\t}\n"
        "\t\t\t\t\treturn fetched;\n"
        "\t\t\t\t}"
    )
    text = text.replace(CACHE_OPEN_ANCHOR, lookup, 1)

    text = text.replace(
        "const isCacheable = FULL_CACHE.some((v) => v === local) || (base === referrer && base.endsWith(CACHED_FILES[0]));",
        "const isCacheable = FULL_CACHE.some((v) => v === local) || PAYLOAD[local] !== undefined"
        " || (base === referrer && base.endsWith(CACHED_FILES[0]));",
        1,
    )
    worker.write_text(text, encoding="utf-8")
    return names


CACHE_STATE_HANDLER = """
// A page cannot read a worker's globals, so it asks. The answer says whether the
// payload is really in its cache and what the browser said when a write failed;
// the landing screen turns the second fact into a sentence (REQ-031).
self.lethebarCacheError = self.lethebarCacheError || "";
self.addEventListener("message", (event) => {
\tif (!event.data || event.data.type !== "lethebar-cache-state") {
\t\treturn;
\t}
\tconst reply = event.ports && event.ports[0];
\t(async () => {
\t\tconst stored = [];
\t\tfor (const name of Object.keys(PAYLOAD)) {
\t\t\tif ((await caches.has(PAYLOAD[name])) && (await (await caches.open(PAYLOAD[name])).match(name))) {
\t\t\t\tstored.push(name);
\t\t\t}
\t\t}
\t\tif (reply) {
\t\t\treply.postMessage({
\t\t\t\tcontrolled: true,
\t\t\t\tstored,
\t\t\t\terror: self.lethebarCacheError || "",
\t\t\t});
\t\t}
\t})();
});
"""


def patch_cache_state(output: Path) -> None:
    """Teach the worker to answer "did you keep the payload?" (REQ-031)."""
    worker = output / SERVICE_WORKER
    if not worker.is_file():
        raise SystemExit(f"{SERVICE_WORKER} is missing; run the export first")
    text = worker.read_text(encoding="utf-8")
    if "lethebar-cache-state" in text:
        return
    if "self.lethebarCacheError" not in text:
        raise SystemExit("the guarded store.put is missing; patch the payload caches first")
    worker.write_text(text + CACHE_STATE_HANDLER, encoding="utf-8")


CACHE_SHIM = """
<script>
// The shell polls this object instead of waiting for the worker before the first
// frame: the notice it feeds is text, so it can arrive one frame late (REQ-031).
(function () {
  var state = { controlled: false, stored: [], error: "", bytes: %d, ready: false };
  window.lethebarCache = state;
  function ask() {
    var worker = navigator.serviceWorker && navigator.serviceWorker.controller;
    if (!worker) { return; }
    var channel = new MessageChannel();
    channel.port1.onmessage = function (event) {
      var answer = event.data || {};
      state.controlled = !!answer.controlled;
      state.stored = answer.stored || [];
      state.error = answer.error || "";
      state.ready = true;
    };
    worker.postMessage({ type: "lethebar-cache-state" }, [channel.port2]);
  }
  if ("serviceWorker" in navigator) {
    navigator.serviceWorker.ready.then(ask).catch(function () {});
    navigator.serviceWorker.addEventListener("controllerchange", ask);
    setTimeout(ask, 1500);
  }
})();
</script>
"""


def inject_cache_probe(output: Path) -> None:
    """Publish what the worker kept, and how big this build's payload is."""
    page = output / "index.html"
    if not page.is_file():
        raise SystemExit("index.html is missing; run the export first")
    text = page.read_text(encoding="utf-8")
    if "lethebarCache" in text:
        return
    if "</body>" not in text:
        raise SystemExit("index.html has no </body>; the shim cannot be placed")
    total = sum((output / name).stat().st_size for name in PAYLOAD_FILES)
    page.write_text(
        text.replace("</body>", (CACHE_SHIM % total) + "</body>"), encoding="utf-8"
    )


IMPORT_BRIDGE = """
<input id="lethebar-import" type="file" accept=".zip" style="display:none">
<script>
// The browser cannot hand a path to the engine, so the player's file arrives
// through this input instead. The bytes go to the shell as base64 through the
// callback the shell registers; nothing leaves the page (REQ-003).
(function () {
  var input = document.getElementById("lethebar-import");
  if (!input) return;
  window.lethebarAskForFile = function () {
    window.lethebarAsked = (window.lethebarAsked || 0) + 1;
    input.click();
  };
  input.addEventListener("change", function () {
    var file = input.files && input.files[0];
    if (!file) { return; }
    var reader = new FileReader();
    reader.onload = function () {
      var bytes = new Uint8Array(reader.result);
      var binary = "";
      for (var index = 0; index < bytes.length; index += 1) {
        binary += String.fromCharCode(bytes[index]);
      }
      input.value = "";
      if (window.lethebarReceiveFile) {
        window.lethebarReceiveFile(window.btoa(binary), file.name);
      }
    };
    reader.readAsArrayBuffer(file);
  });
})();
</script>
"""


def inject_import_bridge(output: Path) -> None:
    """Add the file-input the "Install a pack…" button opens.

    Godot's web export has no way to reach the player's disk: an
    `<input type="file">` in the page is the only door, and the shell asks for it
    through `window.lethebarAskForFile`. The input is generated output, so this
    is a post-export edit of `index.html`; it fails loudly rather than shipping a
    page with a button that does nothing.
    """
    page = output / "index.html"
    if not page.is_file():
        raise SystemExit("index.html is missing; run the export first")
    text = page.read_text(encoding="utf-8")
    if "lethebarAskForFile" in text:
        return
    if "</body>" not in text:
        raise SystemExit("index.html has no </body>; the bridge cannot be placed")
    page.write_text(text.replace("</body>", IMPORT_BRIDGE + "</body>"), encoding="utf-8")


def report(output: Path) -> int:
    missing = [name for name in EXPECTED_FILES if not (output / name).is_file()]
    for path in sorted(output.iterdir()):
        print(f"  {path.name:32} {path.stat().st_size / 1024:9.1f} KB")
    if missing:
        print(f"export is missing {', '.join(missing)}")
        return 1
    print(f"web build written to {output}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help=f"output directory (default: {DEFAULT_OUTPUT})",
    )
    args = parser.parse_args()

    binary = godot_binary()
    appdata = template_directory(binary)
    stage_preset()
    try:
        run_export(binary, args.output, appdata)
    finally:
        PRESET_STAGED.unlink(missing_ok=True)
    precache_payload(args.output)
    payload = layer_payload_caches(args.output)
    patch_navigation_fallback(args.output)
    patch_cache_state(args.output)
    inject_import_bridge(args.output)
    inject_cache_probe(args.output)
    for name, cache in payload.items():
        print(f"  {name:32} cached as {cache}")
    return report(args.output)


if __name__ == "__main__":
    sys.exit(main())
